export function currentLang() {
  const saved = settings.get().lang;
  if (LANGUAGES[saved]) return saved;
  const browser = (navigator.language || 'en').slice(0, 2);
  return LANGUAGES[browser] ? browser : 'en';
}

/** Translate a dictionary label; custom labels and unknown languages fall back to the label itself. */
export const tl = (label, lang = currentLang()) => LABELS[lang]?.[label] ?? label;

/** Translate a UI string; function entries receive the extra args. */
export function tu(key, ...args) {
  const entry = UI[currentLang()][key] ?? UI.en[key];
  return typeof entry === 'function' ? entry(...args) : entry;
}

/** For tests/tools: every dictionary label each language is missing. */
export const missingLabels = (labels) => Object.fromEntries(Object.keys(LABELS).map((l) => [l, labels.filter((x) => !LABELS[l][x])]));
export const uiKeys = () => Object.fromEntries(Object.entries(UI).map(([l, v]) => [l, Object.keys(v)]));
